"""
Opus post-hoc atomic decomposition + per-atom verification
(MCAL_PLAN 3.4, build item #6).

Scope is `settings.ATOMIC_VERIFY_FIELDS`: the five `summary.*` subfields plus
`summary_of_interest`. `summary.overview` is deliberately excluded -- it is a
roll-up whose evidence is carried forward from the five subfields (m2.py:321-336),
so decomposing it would double-count the same atoms.

The pipeline is: prose -> Opus decomposition into atoms -> per-atom
`quote_check.check_quote` against `page +/- 2` -> type-specific checks ->
weighted aggregation into a subfield score. One Opus call per subfield. Opus
judging Opus is deliberate (MCAL_PLAN 3.4): JudgeBench's Sonnet-ceiling warning
applies to weak-judge/strong-writer pairings, and there is no ceiling gap here.

The decomposition prompt is HAND-WRITTEN and NOT tuned on the calibration set.
Tuning it on the same nine documents that fit tau would leak calibration data
into the verifier and void the conformal guarantee (MCAL_PLAN 3.4, 7.5). The
false-negative log exists so the prompt can be improved from *qualitative*
patterns -- missing coreference, missing negation -- never from chasing the
graded-set score.

--------------------------------------------------------------------------
Documented deviation: the plan's stated mechanism does not fit its own evidence
--------------------------------------------------------------------------

MCAL_PLAN 1(3) and 1(4) both attribute their failures to "numeric
hallucination" produced by map-reduce decoupling of `(alternative_label <->
figure)`, and both prescribe the same cure: atomic decomposition plus substring
verification. Checked against the documents, that diagnosis is wrong for both
cases. Reproducible via `tests/test_env_impact_magnitude_75_vs_70.py`.

  * LA Transit `$659 million (Alt. V)` (MCAL_PLAN 1(3)). The figure is on
    pp. 31 / 214 / 215 and is correctly paired with Alternative V -- p. 215
    reads "TOTALS - Alternate #5 ... $659.0 M". Nothing is decoupled. What the
    document adds, on p. 283, is the restriction: "For the Rail/Bus Alternatives
    I-V, the capital costs in 1977 dollars range from 659 million and 1.120
    billion dollars." The summary reported the range without that clause, so a
    true statement about five of eleven alternatives became a false statement
    about all eleven. The corpus minimum is $369 million (Alt. XI), on the same
    table the summary cited.

  * LA Transit `Magnitude 7.5` (MCAL_PLAN 1(4)). p. 146 reads verbatim: "The
    most severe ground shaking that would be felt in the starter line area would
    be generated by a Magnitude 7.5 earthquake occurring on the
    Newport-Inglewood Fault". The figure is present, correctly attached to the
    named fault, and 7.5 also appears in the Figure IV.4 fault table on p. 144.
    The human's 7.0 comes from p. 145, which frames 7.0 as the *maximum
    credible* event for that fault. The document states both figures under
    different framings; the summary carried "maximum credible" across a
    coordination ("San Andreas (Magnitude 8.5 maximum credible) and
    Newport-Inglewood (Magnitude 7.5)") and thereby mislabeled which framing 7.5
    belongs to.

Both claims are SUBSTRING-TRUE. No substring verifier -- not this one, not any
-- can reject them, because the text is there. Only one of the three failures
MCAL_PLAN 1(4) lists is a genuine fabrication and therefore genuinely catchable:
the Lincoln Hwy clause "or important wildlife habitats are affected", which
scores content-token coverage 0.00 against its own cited pages and is caught by
coordination splitting. See `tests/test_lincoln_hwy_wildlife_clause.py`.

So this module adds a `scope_qualifier` field to the atom schema and a
qualifier check, on top of the plan's schema:

  1. An atom that is a range endpoint, a superlative, or a comparison MUST carry
     the document's restricting phrase in `scope_qualifier`. An empty qualifier
     on such an atom is a failure -- `T19_scope_qualifier_dropped`.
  2. The qualifier must itself verify against `page +/- 2`. A qualifier the
     verifier cannot locate is not evidence of scope; it is a second unverified
     claim.
  3. A qualifier present in the located source sentence but absent from the
     atom's own text is a dropped qualifier -- also `T19`.

Rule 1 is what catches the cost case: "capital costs range from $659 million to
$1,450 million" is a range endpoint, so it needs a qualifier, and the only
qualifier the document offers ("For the Rail/Bus Alternatives I-V") is on p. 283
and does not verify against the cited p. 214 window. Either way the atom fails.
Rule 3 is what catches the magnitude case: the p. 146 sentence carries "most
severe ... in the starter line area" and the summary's atom does not.

`T19_scope_qualifier_dropped` already exists in `taxonomy.py` as an
empirically-proposed code (`PROPOSED_TAXONOMY`), so this module does not need a
taxonomy amendment -- only human ratification of T19 at v1.

What the qualifier check still CANNOT do, stated plainly so it does not get
mistaken for a solved problem: it cannot adjudicate between 7.0 and 7.5. The
document contains both. `competing_values` is recorded as an advisory diagnostic
for exactly that reason -- it surfaces the contradiction for a human without
pretending to resolve it, and it is not gating because on OCR'd cost tables the
count of "competing" figures is large and mostly spurious.

--------------------------------------------------------------------------
Why s_citation is the signal that matters here
--------------------------------------------------------------------------

T01_missing_citation is the single most common observed failure -- 10 of the 30
wrong items in the Evaluation sheet, and 4/8 docs on
`summary.public_response` alone. It is currently INVISIBLE to the confidence
composite: `s_quote` is the mean over the evidence entries that exist
(`quote_check.s_quote_for`), so a subfield that cites three pages well and
silently omits citations for four more claims scores the same as one that cites
everything. Averaging over present evidence cannot see absent evidence.

Atom-level citation coverage is the only signal that separates them, because
decomposition enumerates the claims rather than the citations. Measured on the 8
graded docs' 40 summary subfields (`tests/test_atomic_verify.py::TestT01Invisibility`):

    graded "ok, missing citation - pg ..."   n=10   mean s_quote = 0.960
    graded clean "ok"                        n=27   mean s_quote = 0.988

A 0.028 gap. There is no threshold on `s_quote` that separates those populations,
because every citation the extractor DID make verifies -- the defect is a claim it
made without one. Worse, the obvious field-level proxy points the wrong way:
evidence-entries-per-sentence is 2.50 on the missing-citation subfields and 2.10
on the clean ones, so a naive "did it cite enough?" heuristic would rank the
defective subfields as better documented.

`s_citation` (fraction of atoms carrying a page cite) is therefore computed here
and exposed in a shape `confidence.compute_signals(citation_rate=...)` accepts
directly. It carries weight 0 today (MCAL_PLAN 3.3 freezes weights at 0.5/0.5
through v3) but is logged from v1 so weight validation has data when n reaches
~60 -- a signal never recorded cannot be retro-fitted.
"""

