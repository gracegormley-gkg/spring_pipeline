def build_failure_log(
    verifications: Sequence[DocumentVerification],
    grade_set=None,
    *,
    stage: str,
) -> dict:
    """
    The `atomic_verify_failure_log.v(N).json` payload.

    Every atom that FAILS verification is logged with the six MCAL_PLAN 2 keys
    plus the doc/field it came from, and the false-negative audit is embedded so
    a reviewer reading the log sees the gating verdict next to the evidence for
    it.
    """
    entries: list[dict] = []
    for dv in verifications:
        for field, fv in dv.fields.items():
            grade = grade_set.get(dv.doc_id, field) if grade_set is not None else None
            human = grade.raw_grade if grade is not None else None
            for r in fv.failures():
                entries.append(
                    {
                        "doc_id": dv.doc_id,
                        "field": field,
                        "bucket": fv.bucket,
                        "claim_type": r.atom.claim_type,
                        "polarity": r.atom.polarity,
                        "tags": r.tags,
                        "competing_values": r.competing_values,
                        **r.log_entry(human),
                    }
                )

    audit = false_negative_audit(verifications, grade_set, stage=stage)
    total_atoms = sum(len(dv.all_results()) for dv in verifications)
    return {
        "version": settings.normalize_stage(stage),
        "n_docs": len(verifications),
        "n_atoms": total_atoms,
        "n_failures": len(entries),
        "failure_rate": round(len(entries) / total_atoms, 4) if total_atoms else None,
        "false_negative_audit": audit,
        "reason_code_counts": _count_reason_prefixes(entries),
        "failures": entries,
    }


def _count_reason_prefixes(entries: Sequence[dict]) -> dict[str, int]:
    counts: dict[str, int] = {}
    for e in entries:
        for reason in (e.get("failure_reason") or "").split("; "):
            key = reason.split(":", 1)[0].strip()
            if key:
                counts[key] = counts.get(key, 0) + 1
    return dict(sorted(counts.items(), key=lambda kv: (-kv[1], kv[0])))


def save_failure_log(
    verifications: Sequence[DocumentVerification],
    grade_set=None,
    *,
    stage: str,
    draft: bool = True,
) -> Path:
    """Write `atomic_verify_failure_log.v(N).json`."""
    payload = build_failure_log(verifications, grade_set, stage=stage)
    return _write_json(
        settings.artifact_path("atomic_verify_failure_log.json", stage, draft=draft),
        payload,
    )


def load_failure_log(stage: str, *, draft: bool = False) -> dict:
    """Read a written failure log. Raises with an actionable message."""
    path = settings.artifact_path(
        "atomic_verify_failure_log.json", stage, draft=draft
    )
    if not path.exists():
        raise FileNotFoundError(
            f"No atomic-verify failure log for stage {stage}: {path}. It is "
            f"written by `python -m mcal.build --stage {stage}`; if you have not "
            f"run a build yet, {settings.ARTIFACTS_DIR} may not exist at all."
        )
    return json.loads(path.read_text(encoding="utf-8"))
